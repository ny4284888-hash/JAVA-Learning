public class literals {
    public static void main(String[] args) {
        byte age=20; // byte literals can be assigned values from -128 to 127.
        char ch='a'; // single quotes are used for character literals.
        boolean isAdult=true; // boolean literals can be either true or false.
        float pi=3.14f; // float literals require an 'f' suffix.
        double e=2.71828; // double literals can be written without any suffix.
        String name="nandani"; // double quotes are used for string literals.
        int num=100; // integer literals can be assigned values from -2,147,483,648 to 2,147,483,647.
        double salary=50000.50; // double literals can be written without any suffix.
        long population=7800000000L; // long literals require an 'L' suffix.
        short temperature=25; // short literals can be assigned values from -32,768 to 32,767.

        
        System.out.println("Age: " + age);
        System.out.println("Character: " + ch);
        System.out.println("Is Adult: " + isAdult);
        System.out.println("Pi: " + pi);
        System.out.println("E: " + e);
        System.out.println("Name: " + name);
        System.out.println("Number: " + num);
        System.out.println("Salary: " + salary);
        System.out.println("Population: " + population);
        System.out.println("Temperature: " + temperature);
    }
}
